import { createRequire } from 'node:module';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const docRequire = createRequire(resolve(repoRoot, 'doc/package.json'));
const configModulePath = docRequire.resolve('@takazudo/zudo-doc/design-token-panel-config');
const packageJsonPath = resolve(dirname(configModulePath), '../../package.json');
const packageJson = JSON.parse(await readFile(packageJsonPath, 'utf8'));
const { buildDesignTokenPanelConfig } = await import(pathToFileURL(configModulePath).href);

const sourceVersion = String(packageJson.version);
const configs = {
  light: buildDesignTokenPanelConfig('light'),
  dark: buildDesignTokenPanelConfig('dark'),
};
const outputPath = resolve(repoRoot, 'playground/config/zudo-doc-manifest.generated.ts');
const source = `// Generated by scripts/vendor-consumer-manifest.mjs.
// Source: @takazudo/zudo-doc@${sourceVersion}/design-token-panel-config
// Do not edit by hand; rerun the script after intentionally changing the doc dependency.

import type { PanelConfig } from '@takazudo/zdtp';

export const ZUDO_DOC_SOURCE_VERSION = ${JSON.stringify(sourceVersion)};

export const zudoDocConfigs = ${JSON.stringify(configs, null, 2)} as const satisfies Record<'light' | 'dark', PanelConfig>;
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, 'utf8');
console.log(`Vendored @takazudo/zudo-doc@${sourceVersion} panel config to ${outputPath}`);
