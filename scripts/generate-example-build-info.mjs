#!/usr/bin/env node

/**
 * Generate build-time provenance for the first-party example applications.
 *
 * CI must fetch the complete repository history and tags (for example,
 * actions/checkout must use fetch-depth: 0) so the tag relationship can be
 * resolved. Every git/npm lookup is best-effort: an unavailable tool,
 * missing tag, shallow checkout, or network failure produces a valid module
 * with an unknown provenance instead of failing the build.
 */

import { execFile } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { promisify } from 'node:util';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const execFileAsync = promisify(execFile);
const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packagePath = resolve(repoRoot, 'packages/zdtp/package.json');
const DEFAULT_TIMEOUT_MS = 2_000;

function usage() {
  return 'Usage: node scripts/generate-example-build-info.mjs --out <path> [--deploy]';
}

function parseArgs(args) {
  let outPath;
  let deployMode = false;

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === '--deploy' || arg === '--deploy-mode') {
      deployMode = true;
      continue;
    }
    if (arg === '--out') {
      outPath = args[index + 1];
      index += 1;
      continue;
    }
    if (arg.startsWith('--out=')) {
      outPath = arg.slice('--out='.length);
      continue;
    }
    throw new Error(`Unknown argument: ${arg}\n${usage()}`);
  }

  if (!outPath) throw new Error(`Missing --out path\n${usage()}`);
  return { outPath, deployMode };
}

async function run(command, args, options = {}) {
  try {
    const result = await execFileAsync(command, args, {
      cwd: repoRoot,
      encoding: 'utf8',
      timeout: options.timeout ?? DEFAULT_TIMEOUT_MS,
      maxBuffer: 64 * 1024,
    });
    return { ok: true, stdout: result.stdout.trim() };
  } catch {
    return { ok: false, stdout: '' };
  }
}

async function readPanelVersion() {
  try {
    const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
    return typeof packageJson.version === 'string' && packageJson.version.length > 0
      ? packageJson.version
      : 'unknown';
  } catch {
    return 'unknown';
  }
}

async function getGitMetadata(panelVersion) {
  const [shortShaResult, shallowResult] = await Promise.all([
    run('git', ['rev-parse', '--short=7', 'HEAD']),
    run('git', ['rev-parse', '--is-shallow-repository']),
  ]);
  const commitSha = shortShaResult.ok && shortShaResult.stdout ? shortShaResult.stdout : 'unknown';

  if (!shortShaResult.ok || !shallowResult.ok || shallowResult.stdout !== 'false') {
    return { commitSha, provenance: 'unknown' };
  }

  const [headResult, tagResult] = await Promise.all([
    run('git', ['rev-parse', 'HEAD']),
    run('git', ['rev-parse', `refs/tags/v${panelVersion}^{commit}`]),
  ]);
  if (!headResult.ok || !tagResult.ok || !headResult.stdout || !tagResult.stdout) {
    return { commitSha, provenance: 'unknown' };
  }

  if (headResult.stdout === tagResult.stdout) {
    return { commitSha, provenance: 'released' };
  }

  const ancestorResult = await run('git', [
    'merge-base',
    '--is-ancestor',
    tagResult.stdout,
    headResult.stdout,
  ]);
  return {
    commitSha,
    provenance: ancestorResult.ok ? 'ahead' : 'unknown',
  };
}

async function getNpmLatest() {
  const result = await run('npm', ['view', '@takazudo/zdtp@latest', 'version', '--json']);
  if (!result.ok || !result.stdout) return 'unknown';

  try {
    const parsed = JSON.parse(result.stdout);
    return typeof parsed === 'string' && parsed.length > 0 ? parsed : 'unknown';
  } catch {
    return 'unknown';
  }
}

function renderModule({ panelVersion, commitSha, builtAt, npmLatest, provenance, deployMode }) {
  return `// Generated by scripts/generate-example-build-info.mjs.\n// Do not edit by hand; rerun the generator after changing the panel or build mode.\n\nexport const PANEL_VERSION: string = ${JSON.stringify(panelVersion)};\nexport const COMMIT_SHA: string = ${JSON.stringify(commitSha)};\nexport const BUILT_AT: string = ${JSON.stringify(builtAt)};\nexport const NPM_LATEST: string = ${JSON.stringify(npmLatest)};\nexport const PROVENANCE: 'released' | 'ahead' | 'unknown' = ${JSON.stringify(provenance)};\nexport const DEPLOY_MODE: boolean = ${deployMode};\n`;
}

const { outPath, deployMode } = parseArgs(process.argv.slice(2));
const panelVersion = await readPanelVersion();
const [{ commitSha, provenance }, npmLatest] = await Promise.all([
  getGitMetadata(panelVersion),
  getNpmLatest(),
]);
const outputPath = resolve(process.cwd(), outPath);
const source = renderModule({
  panelVersion,
  commitSha,
  builtAt: new Date().toISOString(),
  npmLatest,
  provenance,
  deployMode,
});

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, 'utf8');
console.log(`Generated example build info at ${outputPath}`);
